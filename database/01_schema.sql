-- FORNITORI / schema PostgreSQL v0.1 / 03-11-2026
-- Schema applicativo validato in CI con PostgreSQL 18.
BEGIN;
CREATE TABLE IF NOT EXISTS app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(200) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    ruolo VARCHAR(20) NOT NULL CHECK (ruolo IN ('responsabile','autista')),
    nome VARCHAR(150) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    targa VARCHAR(20) NOT NULL UNIQUE,
    tipologia TEXT NOT NULL,
    portata_t NUMERIC(6,2) NOT NULL CHECK (portata_t>0),
    base_indirizzo TEXT NOT NULL, base_citta VARCHAR(100) NOT NULL,
    base_lat NUMERIC(10,6) NOT NULL CHECK(base_lat BETWEEN -90 AND 90),
    base_lng NUMERIC(10,6) NOT NULL CHECK(base_lng BETWEEN -180 AND 180)
);
CREATE TABLE IF NOT EXISTS drivers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES app_users(id),
    nome VARCHAR(150) NOT NULL, telefono VARCHAR(32) NOT NULL,
    vehicle_id BIGINT NOT NULL UNIQUE REFERENCES vehicles(id),
    stato_seed VARCHAR(20) NOT NULL CHECK(stato_seed IN ('disponibile','occupato')),
    zona VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS insurance_companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(200) NOT NULL,
    telefono_centrale VARCHAR(32), email_sinistri VARCHAR(200)
);
CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(150) NOT NULL,
    telefono VARCHAR(32) NOT NULL,
    targa VARCHAR(20) NOT NULL,
    targa_norm VARCHAR(20) NOT NULL UNIQUE,
    modello_veicolo VARCHAR(150),
    company_id BIGINT NOT NULL REFERENCES insurance_companies(id),
    numero_polizza VARCHAR(100) NOT NULL,
    scadenza_polizza DATE NOT NULL,
    citta_residenza VARCHAR(150)
);
CREATE TABLE IF NOT EXISTS workshops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(200) NOT NULL, indirizzo TEXT NOT NULL, citta VARCHAR(120) NOT NULL,
    lat NUMERIC(10,6) NOT NULL CHECK(lat BETWEEN -90 AND 90),
    lng NUMERIC(10,6) NOT NULL CHECK(lng BETWEEN -180 AND 180)
);
CREATE TABLE IF NOT EXISTS pricing_config (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    uscita_eur NUMERIC(10,2) NOT NULL CHECK (uscita_eur>=0),
    tariffa_km_eur NUMERIC(10,2) NOT NULL CHECK (tariffa_km_eur>=0),
    maggiorazione_notturna NUMERIC(5,4) NOT NULL CHECK (maggiorazione_notturna BETWEEN 0 AND 1),
    night_start TIME NOT NULL, night_end TIME NOT NULL,
    timeout_proposta_min INTEGER NOT NULL CHECK (timeout_proposta_min>=1)
);
CREATE TABLE IF NOT EXISTS missions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codice VARCHAR(40) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    driver_id BIGINT REFERENCES drivers(id),
    stato VARCHAR(20) NOT NULL CHECK(stato IN ('nuova','proposta','accettata','eseguita','non_accettata','scaduta')),
    tipo_intervento VARCHAR(40) NOT NULL CHECK(tipo_intervento IN ('traino','riparazione_sul_posto')),
    canale_origine VARCHAR(20) NOT NULL CHECK(canale_origine IN ('centrale','whatsapp','telegram')),
    descrizione_problema TEXT NOT NULL,
    origine_indirizzo TEXT NOT NULL,
    origine_lat NUMERIC(10,6),
    origine_lng NUMERIC(10,6),
    workshop_id BIGINT REFERENCES workshops(id),
    km_stimati NUMERIC(10,2) CHECK(km_stimati>=0),
    km_effettivi NUMERIC(10,2) CHECK(km_effettivi>=0),
    creata_il TIMESTAMPTZ NOT NULL,
    proposta_il TIMESTAMPTZ,
    scadenza_il TIMESTAMPTZ,
    accettata_il TIMESTAMPTZ,
    chiusa_il TIMESTAMPTZ,
    notturno BOOLEAN,
    costo_calcolato NUMERIC(10,2) CHECK(costo_calcolato>=0),
    costo_finale NUMERIC(10,2) CHECK(costo_finale>=0),
    rettifica_motivo TEXT,
    rettifica_utente_id BIGINT REFERENCES app_users(id),
    is_fixture BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_workshop_traino CHECK (tipo_intervento <> 'traino' OR workshop_id IS NOT NULL),
    CONSTRAINT ck_mission_coordinate CHECK (
        (origine_lat IS NULL AND origine_lng IS NULL) OR
        (origine_lat BETWEEN -90 AND 90 AND origine_lng BETWEEN -180 AND 180)
    ),
    CONSTRAINT ck_mission_completed CHECK (stato <> 'eseguita' OR (chiusa_il IS NOT NULL AND km_effettivi IS NOT NULL AND costo_finale IS NOT NULL))
);
-- Solo transazioni LIVE: proibisce anche una seconda proposta pendente allo stesso autista.
-- Le incoerenze del foglio Excel rimangono rilevabili nei record is_fixture=TRUE.
CREATE UNIQUE INDEX IF NOT EXISTS uq_driver_active_live
  ON missions(driver_id) WHERE is_fixture=FALSE AND driver_id IS NOT NULL AND stato IN ('proposta','accettata');
CREATE INDEX IF NOT EXISTS ix_missions_state ON missions(stato,is_fixture);
CREATE INDEX IF NOT EXISTS ix_missions_customer ON missions(customer_id);
CREATE TABLE IF NOT EXISTS mission_proposals (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    mission_id BIGINT NOT NULL REFERENCES missions(id),
    driver_id BIGINT NOT NULL REFERENCES drivers(id),
    stato VARCHAR(20) NOT NULL CHECK(stato IN ('proposta','accettata','non_accettata','scaduta','chiusa')),
    proposta_il TIMESTAMPTZ NOT NULL,
    scadenza_il TIMESTAMPTZ NOT NULL,
    risposta_il TIMESTAMPTZ,
    is_fixture BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_proposal_deadline CHECK (scadenza_il > proposta_il)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_proposal_seed_idempotent ON mission_proposals(mission_id,driver_id,proposta_il);
CREATE UNIQUE INDEX IF NOT EXISTS uq_one_open_proposal
  ON mission_proposals(mission_id) WHERE stato='proposta' AND is_fixture=FALSE;
CREATE TABLE IF NOT EXISTS mission_notes (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    mission_id BIGINT NOT NULL REFERENCES missions(id),
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    testo TEXT NOT NULL CHECK(length(btrim(testo)) BETWEEN 1 AND 2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS mission_events (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    mission_id BIGINT NOT NULL REFERENCES missions(id),
    actor_user_id BIGINT REFERENCES app_users(id),
    event_type VARCHAR(50) NOT NULL,
    detail JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS chat_sessions (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    channel VARCHAR(20) NOT NULL CHECK(channel IN ('telegram','whatsapp')),
    external_chat_id VARCHAR(120) NOT NULL,
    telefono_verificato VARCHAR(40),
    stato_dialogo VARCHAR(30) NOT NULL DEFAULT 'attesa_targa',
    context JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(channel,external_chat_id)
);
CREATE TABLE IF NOT EXISTS notifications_outbox (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    event_key VARCHAR(140) NOT NULL UNIQUE,
    mission_id BIGINT NOT NULL REFERENCES missions(id),
    channel VARCHAR(20) NOT NULL,
    destinatario VARCHAR(120) NOT NULL,
    payload JSONB NOT NULL,
    stato VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(stato IN ('PENDING','SENT','FAILED')),
    tentativi INTEGER NOT NULL DEFAULT 0,
    ultimo_errore TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at TIMESTAMPTZ
);
-- L'applicazione esegue proposta/accetta/rifiuta/chiudi sotto transazioni e lock SQL.
-- Restrizioni per ruoli e permessi vanno applicate nel service Spring Security.
COMMIT;
